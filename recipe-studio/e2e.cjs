'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright-core');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_BIN||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];
  page.on('pageerror',err=>errors.push(err.message));
  const resp=await page.goto('http://127.0.0.1:8765/recipe-studio/?brand=berbena',{waitUntil:'networkidle'});
  assert(resp.ok(),'studio loads');
  await page.locator('.recipegrid .card').first().waitFor();
  assert.equal(await page.locator('.recipegrid .card').count(),44,'berbena shows all 44 available editorial recipes');
  assert.equal(await page.locator('[data-view="plan"]').count(),0,'berbena never shows weekly menu control');
  assert.equal(await page.locator('[data-days]').count(),0,'berbena never shows Palleta planner');
  assert(await page.getByText('[Unverified]',{exact:false}).count(),'recipe calories must be visibly labeled unverified');
  const firstCard=page.locator('.recipegrid .card').first();
  assert(await firstCard.getByText('ккал/порция',{exact:false}).count(),'recipe card shows calorie estimate');
  await firstCard.locator('[data-fav]').click();
  await page.locator('[data-view="favorites"]').click();
  assert.equal(await page.locator('.recipegrid .card').count(),1,'favorites filtered');
  await page.locator('.recipegrid .card [data-open]').first().click();
  await page.getByRole('heading',{name:'Готовим по шагам'}).waitFor();
  const calorieLabel=await page.locator('[aria-label="Калорийность"] h2').innerText();
  assert(calorieLabel.includes('[Unverified]'),'calorie estimate labeled');
  const amount1=await page.locator('.panel .shopping strong').first().innerText();
  await page.locator('[data-cookdays="2"]').click();
  const amount2=await page.locator('.panel .shopping strong').first().innerText();
  assert.notEqual(amount1,amount2,'two days doubles ingredient amounts');
  assert.equal(await page.locator('[aria-label="Калорийность"] h2').innerText(),calorieLabel,'per-serving kcal unaffected by total servings');
  await page.locator('#cook-people').selectOption('2');
  assert(await page.getByText('4 порц.',{exact:false}).count(),'whole cooked recipe has four portions');
  await page.locator('[data-next]').click();
  assert(await page.getByText(/Шаг [12] из/).count(),'guided cook steps visible');
  await page.locator('[data-back]').click();
  await page.locator('[data-brand="palleta"]').click();
  await page.getByRole('heading',{name:'Меню на 3 дня'}).waitFor();
  assert.equal(await page.locator('.meal').count(),9,'palleta: three-day menu');
  assert.equal(await page.locator('.recipegrid').count(),0,'palleta hides recipe browsing catalog');
  assert.equal(await page.locator('[data-open]').count(),0,'palleta hides cooking mode buttons');
  assert.equal(await page.getByText('ккал',{exact:false}).count(),0,'palleta never shows calorie estimates');
  await page.locator('#days').selectOption('7');
  assert.equal(await page.locator('.meal').count(),21,'palleta seven-day menu');
  await page.locator('[data-repeat="0-breakfast"]').click();
  const breakfasts=await page.locator('.meal b').allInnerTexts();
  assert.equal(breakfasts[0],breakfasts[3],'palleta repeated same breakfast on next day');
  await page.locator('input[data-home="potato"]').check();
  assert(await page.getByText('Уже есть дома').count()>=1,'pantry displayed');
  assert(await page.getByText('Точную стоимость корзины пока назвать нельзя',{exact:false}).count(),'prices not promised');
  assert(await page.getByText('Мясо, отсутствующее в ассортименте магазина',{exact:false}).count(),'meat excluded');
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Меню на 7 дней'}).waitFor();
  assert.deepEqual(errors,[],'no client-side JS errors');
  console.log('PASS mobile Chrome: exclusive berbena calories/cook, exclusive Palleta menu/basket, no false current prices');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});